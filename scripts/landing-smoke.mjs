import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const base = process.env.LANDING_URL || 'http://127.0.0.1:5191'
const browser = await chromium.launch({ channel: 'msedge', headless: true })
await mkdir('test-results/landing', { recursive: true })
try {
 const page = await browser.newPage({viewport:{width:1440,height:1000}})
 const errors = [], media = []
 page.on('pageerror', e => {errors.push(e.message);console.log('PAGEERROR',e.message)})
 page.on('console', m=>{if(m.type()==='error')console.log('CONSOLE',m.text())})
 page.on('request', request => { if (/timelens-tvc-.*\.mp4/.test(request.url())) media.push(request.url()) })
 await page.route('**://*/api/**', route => route.fulfill({status:200,contentType:'application/json',body:'{}'}))
 await page.goto(base, {waitUntil:'domcontentloaded',timeout:90000})
 await page.getByRole('button',{name:'Từ chối tất cả',exact:true}).click()
 await page.evaluate(() => Promise.race([document.fonts.ready,new Promise(r=>setTimeout(r,3000))]))
 await page.getByRole('heading',{name:/Lịch sử không/}).waitFor()
 console.log('Landing loaded')
  assert.equal(media.length,0,'Video must not download before play')
 await page.getByRole('button',{name:'⊞ Mở mô hình 3D',exact:true}).click()
 await page.getByRole('region',{name:'Không gian mô hình 3D mũ cối'}).waitFor()
 await page.waitForFunction(()=>document.querySelector('.tl-spatial-canvas')?.style.visibility==='visible' || document.querySelector('.tl-spatial-fallback p')?.textContent?.includes('Chưa thể'),{},{timeout:90000}).catch(async e=>{await page.screenshot({path:'test-results/landing/model-error.png'});throw e})
 await page.screenshot({path:'test-results/landing/model-3d.png'})
 await page.keyboard.press('Escape')
 assert.equal(await page.locator('.tl-spatial-scene').count(),0)
 await page.evaluate(()=>document.activeElement?.blur())
 await page.screenshot({path:'test-results/landing/desktop-hero.png'})
 for(const width of [390,768,1280,1920]) {
  await page.setViewportSize({width,height:1000})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`No horizontal overflow ${width}`)
  if(width===390){
   await page.getByRole('button',{name:'Mở điều hướng',exact:true}).click()
   await page.getByRole('navigation',{name:'Điều hướng trang chủ'}).getByRole('link',{name:'Trang chủ',exact:true}).waitFor({state:'visible'})
   await page.keyboard.press('Escape')
   assert.equal(await page.getByRole('button',{name:'Mở điều hướng',exact:true}).getAttribute('aria-expanded'),'false')
   await page.screenshot({path:'test-results/landing/mobile-hero.png'})
  }
 }
 await page.setViewportSize({width:1440,height:1000})
 const tabs=page.getByRole('tab')
 for(let index=0;index<6;index++){
  await tabs.nth(index).click()
  assert.equal(await tabs.nth(index).getAttribute('aria-selected'),'true')
  const image=page.getByRole('tabpanel').locator('img')
  await image.evaluate(img=>img.decode())
  assert.ok(await image.evaluate(img=>img.naturalWidth>0),'Feature image loads')
 }
 await tabs.nth(0).focus();await page.keyboard.press('End')
 assert.equal(await tabs.nth(5).getAttribute('aria-selected'),'true')
 await page.locator('.tl-faq summary').first().click()
 assert.equal(await page.locator('.tl-faq details').first().getAttribute('open'),'')
 await page.locator('#technology').scrollIntoViewIfNeeded(); await page.waitForTimeout(850)
 await page.locator('#technology').screenshot({path:'test-results/landing/technology.png'})
 await page.locator('#experiences').scrollIntoViewIfNeeded(); await page.waitForTimeout(850)
 await page.locator('#experiences').screenshot({path:'test-results/landing/experiences.png'})
 await page.locator('#tvc').scrollIntoViewIfNeeded(); await page.waitForTimeout(850)
 await page.locator('#tvc').screenshot({path:'test-results/landing/tvc.png'})
 assert.equal(media.length,0,'Scrolling must not preload TVC')
 console.log('Layout and showcase passed')
 await page.getByRole('button',{name:'Phát TVC giới thiệu TimeLens',exact:true}).click()
 const video=page.locator('#tvc video')
 await video.evaluate(v=>new Promise((resolve,reject)=>{if(v.readyState>=2)return resolve();v.addEventListener('loadeddata',resolve,{once:true});v.addEventListener('error',()=>reject(new Error('Video failed')),{once:true});setTimeout(()=>reject(new Error('Video timeout')),90000)}))
 await page.waitForTimeout(1200)
 assert.ok(await video.evaluate(v=>v.currentTime>0),'Video starts')
 await video.evaluate(v=>{v.currentTime=65})
 await page.waitForTimeout(1000)
 assert.equal(await page.getByLabel('Chất lượng TVC',{exact:true}).count(),0,'Obsolete quality dock removed')
 assert.ok(await video.evaluate(v=>v.videoWidth===1920),'1080p actual resolution')
 const range=await page.request.get(base+'/films/timelens-tvc-1080-v1.mp4',{headers:{Range:'bytes=0-1023'}})
 assert.equal(range.status(),206)
 const bytes=await range.body(); assert.equal(bytes.toString('ascii',4,8),'ftyp')
 assert.deepEqual(errors,[])
 const reduced=await browser.newPage({reducedMotion:'reduce',viewport:{width:390,height:844}})
 await reduced.route('**://*/api/**', route=>route.fulfill({status:200,contentType:'application/json',body:'{}'}))
 await reduced.goto(base);await reduced.getByRole('heading',{name:/Lịch sử không/}).waitFor()
 assert.equal(await reduced.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
 console.log(JSON.stringify({passed:true,widths:[390,768,1280,1920],mediaRequests:media.length,errors}))
} finally { await browser.close() }
