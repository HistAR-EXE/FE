import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const base=process.env.LANDING_URL||'http://127.0.0.1:5191'
const browser=await chromium.launch({channel:'msedge',headless:true})
const consent=JSON.stringify({analytics:false,camera:false,gps:false})
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}})
 await page.addInitScript(consent=>{
  const data={histar_consent_v1:consent,timelens_token:'landing-ui-fixture',timelens_user_id:'landing-test',timelens_display_name:'Người thử nghiệm',timelens_email_verified:'1',timelens_tier:'PREMIUM'}
  Object.entries(data).forEach(([k,v])=>localStorage.setItem(k,v))
 },consent)
 await page.route('**://*/api/**',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({success:true,data:{id:'landing-test',email:'ui@example.test',displayName:'Người thử nghiệm',tier:'PREMIUM',role:'USER',avatarUrl:null,emailVerified:true,activeVisitSites:[]}})}))
 await page.goto(base,{waitUntil:'domcontentloaded'})
 const account=page.getByRole('button',{name:'Mở tài khoản cá nhân',exact:true})
 await account.click()
 assert.equal(await page.getByRole('link',{name:'Lịch sử thanh toán',exact:true}).getAttribute('href'),'/settings')
 await page.getByRole('link',{name:'Hồ sơ cá nhân',exact:true}).focus();await page.keyboard.press('Escape')
 assert.equal(await account.evaluate(e=>e===document.activeElement),true,'Escape restores account focus')
 await page.getByRole('link',{name:'Khám phá TimeLens',exact:false}).first().focus();await page.keyboard.press('Escape')
 assert.equal(await page.evaluate(()=>document.activeElement.textContent.includes('Khám phá TimeLens')),true,'Escape outside menu preserves focus')
 await page.getByRole('button',{name:'Phát TVC giới thiệu TimeLens',exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('#tvc video')?.readyState>=2)
 await page.locator('#tvc video').evaluate(v=>{v.currentTime=42;void v.play()})
 await page.waitForTimeout(300)
 assert.equal(await page.getByLabel('Chất lượng TVC',{exact:true}).count(),0)
 assert.equal(await page.locator('#tvc video').evaluate(v=>v.paused),false,'Playback continues without removed quality dock')
 await page.close()
 const lost=await browser.newPage({viewport:{width:1280,height:900}})
 await lost.addInitScript(consent=>localStorage.setItem('histar_consent_v1',consent),consent)
 await lost.route('**://*/api/**',route=>route.fulfill({status:200,contentType:'application/json',body:'{}'}))
 await lost.route('**/assets/hat.glb',async route=>{await new Promise(r=>setTimeout(r,1500));await route.continue().catch(()=>{})})
 await lost.goto(base,{waitUntil:'domcontentloaded'})
 await lost.getByRole('button',{name:'⊞ Mở mô hình 3D',exact:true}).click()
 await lost.locator('.tl-spatial-canvas canvas').waitFor({state:'attached'})
 await lost.locator('.tl-spatial-canvas canvas').dispatchEvent('webglcontextlost',{cancelable:true})
 await lost.getByText('Chưa thể mở không gian 3D trên thiết bị này.',{exact:true}).waitFor()
 await lost.waitForTimeout(2200)
 assert.equal(await lost.locator('.tl-spatial-canvas').evaluate(e=>e.style.visibility),'hidden','Context loss during GLB load keeps fallback')
 await lost.close()
 const fallback=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'})
 await fallback.addInitScript(consent=>{
  localStorage.setItem('histar_consent_v1',consent)
  const original=HTMLCanvasElement.prototype.getContext
  HTMLCanvasElement.prototype.getContext=function(type,...args){return /webgl/.test(type)?null:original.call(this,type,...args)}
 },consent)
 await fallback.route('**://*/api/**',route=>route.fulfill({status:200,contentType:'application/json',body:'{}'}))
 await fallback.goto(base,{waitUntil:'domcontentloaded'})
 await fallback.getByRole('button',{name:'⊞ Mở mô hình 3D',exact:true}).click()
 await fallback.getByText('Chưa thể mở không gian 3D trên thiết bị này.',{exact:true}).waitFor({timeout:60000})
 await fallback.screenshot({path:'test-results/landing/mobile-3d-fallback.png'})
 await fallback.getByRole('button',{name:'Đóng không gian 3D',exact:true}).click()
 await fallback.route('**/films/timelens-tvc-*.mp4',route=>route.fulfill({status:404,body:'missing'}))
 await fallback.getByRole('button',{name:'Phát TVC giới thiệu TimeLens',exact:true}).click()
 await fallback.getByText('Chưa tải được TVC.',{exact:true}).waitFor()
 await fallback.unroute('**/films/timelens-tvc-*.mp4')
 await fallback.getByRole('button',{name:'Thử lại',exact:true}).click()
 await fallback.waitForFunction(()=>document.querySelector('#tvc video')?.readyState>=2)
 assert.ok(await fallback.locator('#tvc video').evaluate(v=>v.duration>158&&v.duration<159))
 assert.equal(await fallback.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
 console.log(JSON.stringify({passed:true,authenticatedHeader:'mocked profile',playback:true,webglFallback:true,videoErrorRetry:true}))
} finally {await browser.close()}
